# Attach an explicit time time zone to "naive" `datetime` objects. A "naive" `datetime` doen't have a
# time zone. Such objects are typically interpreted as representing local time, but could be confused
# for objects representing UTC. This helper function disambiguates by explicitly attaching the local
# time zone to `datetime` objects that don't already have an explicit time zone.
def ensure_has_timezone(
    *,
    when: IMPORT_typing.Optional[IMPORT_datetime_datetime | IMPORT_datetime_timedelta] = None,
) -> IMPORT_typing.Optional[IMPORT_datetime_datetime | IMPORT_datetime_timedelta]:
    if when is not None and isinstance(when, IMPORT_datetime_datetime) and when.tzinfo is None:
        return when.replace(tzinfo=IMPORT_tzlocal_get_localzone())
    return when

